#!/usr/bin/env python3
"""Writes ClaudeCompanion/Drops.lua: the pack's drop chances, for the in-game grind panel.

  python3 -I tools/make-drops.py [gamedata.js] [Drops.lua]          write it
  python3 -I tools/make-drops.py --check [gamedata.js] [Drops.lua]  exit 1 if it is out of date (CI)

The pack (web/data/gamedata.js `src`, built from ForeverDB by gamedata/build.py) stays the one source:
this file is only that data in a form the game can load. Only chances ForeverDB measured on Forever kills
(rateSrc 'm') are kept: Classic rates are left out on purpose, so the panel says "rate unknown" instead.
Per item: the creatures that drop it, by name, with the chance in percent and how many Forever kills it
was measured on.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = [a for a in sys.argv[1:] if a != '--check']
PACK = args[0] if args else os.path.join(ROOT, 'ClaudeCompanion', 'web', 'data', 'gamedata.js')
OUT = args[1] if len(args) > 1 else os.path.join(ROOT, 'ClaudeCompanion', 'Drops.lua')


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'


def num(x):
    x = round(float(x), 3)
    return str(int(x)) if x == int(x) else repr(x)


def build(pack):
    s = open(pack, encoding='utf-8').read()
    g = json.loads(s[s.index('=') + 1:s.rstrip().rindex(';')])
    lines = []
    for iid in sorted(g['src'], key=int):
        rows = [r for r in g['src'][iid]
                if r[0] == 'drop' and r[2] and isinstance(r[3], (int, float)) and r[3] > 0 and r[11] == 'm'
                and r[1] and not r[1].startswith('#')]
        if not rows: continue
        best = {}
        for r in rows:  # one entry per creature name (the grind counts kills by name)
            n = r[12] if isinstance(r[12], int) else 0
            if r[1] not in best or n > best[r[1]][1]: best[r[1]] = (r[3], n)
        cells = ','.join(f'{lua_str(n)},{num(p)},{k}' for n, (p, k) in sorted(best.items()))
        lines.append(f'[{int(iid)}]={{{cells}}},')
    head = ('-- Generated by tools/make-drops.py from web/data/gamedata.js (ForeverDB drop chances measured on Forever). Do not edit.\n'
            f'-- Pack built {g.get("built")}. Per item: creature name, chance in percent, Forever kills it was measured on. No Classic rates.\n'
            'local _, ns = ...\n'
            'ns.DROPS = {\n')
    return head + '\n'.join(lines) + '\n}\n'


text = build(PACK)
if '--check' in sys.argv:
    cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if cur != text: sys.exit(f'{OUT} is out of date: run python3 -I tools/make-drops.py')
    print('Drops.lua matches the pack')
else:
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f: f.write(text)
    print(f'wrote {OUT}: {text.count(chr(10)) - 5} items, {len(text) // 1024} KB')
